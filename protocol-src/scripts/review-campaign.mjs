#!/usr/bin/env node
/**
 * review-campaign.mjs — dependency-free campaign review sheet generator.
 *
 * Produces the same stage-by-stage sheet that was hand-built for ARC_BAKI:
 * every FIT prescription (movement, sets x reps/sec, category, rest) and every
 * FIGHT round (goal, combo seed, complexity), plus an auto-flag section that
 * looks for the problems found in the Baki review.
 *
 *   node protocol-src/scripts/review-campaign.mjs ARC_ULTRAEGO
 *   node protocol-src/scripts/review-campaign.mjs ARC_ULTRAEGO --stdout
 *   node protocol-src/scripts/review-campaign.mjs --all
 *
 * Default output: protocol-src/reviews/<CAMPAIGN_ID>-review.md
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const CAMPAIGNS = join(HERE, "..", "data", "campaigns");
const REVIEWS = join(HERE, "..", "reviews");

// The Arcade ladder caps a campaign at this many stages — anything past it is
// silently dropped by data/arcadeCampaignSeries.js, so it must be flagged.
const ARCADE_MAX_STAGES = 10;

const load = (p) => JSON.parse(readFileSync(p, "utf8"));
const arr = (x) => (Array.isArray(x) ? x : x?.stages || x?.modules || []);
const stageOf = (id) => Number(String(id).split("_S")[1]?.slice(0, 2)) || 0;

function doseOf(ex) {
  if (ex.count_mode === "none") return `1 × ${ex.duration_sec}s (uncounted)`;
  if (ex.count_mode === "time" || ex.duration_sec != null) return `${ex.sets} × ${ex.duration_sec}s`;
  return `${ex.sets} × ${ex.reps}`;
}

function seedOf(round) {
  const cs = round.combo_spec;
  if (!cs) return "*no combo_spec*";
  const strikes = cs.allowed_strikes;
  if (!strikes?.length) return "*cue-based*";
  const label = "`" + strikes.join(", ") + "` · " + (cs.complexity || "standard");
  return cs.mixed_with_cue ? `**mixed** — ${label}, interleaved with technique cues` : label;
}

function review(cid) {
  const dir = join(CAMPAIGNS, cid);
  const campaign = load(join(dir, "campaign.json"));
  const stages = arr(load(join(dir, "stages.json")))
    .slice().sort((a, b) => (a.stage_number || 0) - (b.stage_number || 0));
  const rawModules = load(join(dir, "modules.json"));
  const modules = arr(rawModules);
  const byId = new Map(modules.map((m) => [m.module_id, m]));

  const flags = [];
  let generated = 0, cue = 0, mixed = 0;
  const out = [];

  // ── header ──────────────────────────────────────────────────────────────
  const fitMods = modules.filter((m) => m.module_type === "fit");
  const fightMods = modules.filter((m) => m.module_type === "fight");
  const tierMap = fitMods
    .map((m) => [stageOf(m.module_id), m.tier])
    .sort((a, b) => a[0] - b[0]);
  const tierRuns = [];
  for (const [n, t] of tierMap) {
    const last = tierRuns[tierRuns.length - 1];
    if (last && last.tier === t) last.end = n;
    else tierRuns.push({ tier: t, start: n, end: n });
  }

  out.push(`# ${cid} — "${campaign.name}" · campaign review sheet`, "");
  out.push(`Generated by \`protocol-src/scripts/review-campaign.mjs\`.`);
  out.push(`**${stages.length} stages · ${modules.length} modules** · tier map ` +
    tierRuns.map((r) => `${r.tier} = S${r.start}${r.end !== r.start ? `–S${r.end}` : ""}`).join(", ") + ".", "");
  out.push("**Stored numbers are the NORMAL baseline.** The app re-resolves easy/hard",
    "at runtime from the volume ladder in `arcade-session-standards.json` by",
    "tier + category.", "");

  // ── per stage ───────────────────────────────────────────────────────────
  const body = [];
  for (const st of stages) {
    const ids = Object.values(st.paths || {}).flatMap((p) => p.module_ids || []);
    const fit = ids.map((i) => byId.get(i)).filter((m) => m?.module_type === "fit");
    const fight = ids.map((i) => byId.get(i)).filter((m) => m?.module_type === "fight");
    const tier = fit[0]?.tier || fight[0]?.tier || "—";

    body.push("---", "");
    body.push(`## S${String(st.stage_number).padStart(2, "0")} · ${st.title} — *${st.phase} · ${st.persona || "—"}* · ${tier}`, "");
    if (st.purpose) body.push(`> ${st.purpose}`, "");

    for (const m of fit) {
      body.push(`**FIT — ${m.title}** · ${m.duration_min} min`);
      const presc = m.prescription || [];
      if (!presc.length) {
        body.push("", "> ⚠️ No counted `prescription` — this module has not had the arcade", "> session standard applied.", "");
        flags.push(`**${m.module_id}** has no counted \`prescription\` — the volume ladder and counted-set runner can't drive it.`);
      } else {
        body.push("| Exercise | Sets × Reps | Category | Rest |", "|---|---|---|---|");
        for (const ex of presc) {
          const cat = ex.load_type === "weighted" ? `${ex.category} (weighted)` : ex.category;
          body.push(`| ${ex.name} | ${doseOf(ex)} | ${cat} | ${ex.rest_sec ? ex.rest_sec + "s" : "—"} |`);
        }
        body.push("");
      }
    }

    for (const m of fight) {
      const rounds = m.rounds || [];
      const len = rounds[0]?.length_sec ? `${Math.round(rounds[0].length_sec / 60)}min` : "?";
      const rest = rounds[0]?.rest_sec != null ? `${rounds[0].rest_sec}s` : "?";
      body.push(`**FIGHT — ${m.title}** · ${m.duration_min} min · ${rounds.length} × ${len} / ${rest}`);
      body.push("| R | Goal | Combo seed |", "|---|---|---|");

      let stageGen = 0, singles = 0;
      for (const r of rounds) {
        body.push(`| ${r.index} | ${r.goal} | ${seedOf(r)} |`);
        const cs = r.combo_spec || {};
        if (cs.allowed_strikes?.length) { generated++; stageGen++; if (cs.complexity === "single") singles++; }
        else cue++;
        if (cs.mixed_with_cue) mixed++;
      }
      body.push("");
      if (m.finishers?.movements?.length) {
        const f = m.finishers;
        body.push(`Finisher: ${f.movements.join(" + ")} — ${f.sets} × ${f.work_sec}s${f.capped ? " (capped)" : ""}.`, "");
      }

      // per-module flags
      if (!m.tier) flags.push(`**${m.module_id}** has no \`tier\` (fit modules do) — the two halves of the stage aren't symmetrical.`);
      if (rounds.length && stageGen === 0) {
        flags.push(`**${m.module_id}** (S${stageOf(m.module_id)}) has **zero generated rounds** — all ${rounds.length} are cue-based, so no combos get called for the whole stage.`);
      }
      if (rounds.length === 1 && rounds[0].length_sec > 600) {
        flags.push(`**${m.module_id}** is a single ${Math.round(rounds[0].length_sec / 60)}-minute block rather than short rounds — it needs splitting into 5–6 rounds like the other campaigns.`);
      }
      if (stageGen > 0 && singles >= Math.max(3, Math.ceil(stageGen * 0.6))) {
        flags.push(`**${m.module_id}** (S${stageOf(m.module_id)}) has ${singles} of ${stageGen} generated rounds at \`complexity: "single"\`. Single rounds are exempt from the 60/40 variety rule, so the stage risks feeling like one repeated punch — the Baki Stage 4 problem.`);
      }
    }
  }

  // ── campaign-level flags ────────────────────────────────────────────────
  if (stages.length > ARCADE_MAX_STAGES) {
    const dropped = stages
      .filter((s) => s.phase !== "final_boss")
      .slice(ARCADE_MAX_STAGES - 1)
      .map((s) => `S${s.stage_number} "${s.title}"`);
    flags.push(`**Campaign is ${stages.length} stages but the Arcade caps at ${ARCADE_MAX_STAGES}.** ` +
      `\`capToArcadeLength\` in \`data/arcadeCampaignSeries.js\` keeps stages 1–${ARCADE_MAX_STAGES - 1} plus the boss, ` +
      `so these never play: ${dropped.join(", ")}. Fold their content forward and renumber the boss, ` +
      `the way ARC_BAKI was restructured.`);
  }
  if (campaign.stage_count !== stages.length) {
    flags.push(`\`campaign.stage_count\` is ${campaign.stage_count} but there are ${stages.length} stages.`);
  }
  // consecutive stages with no combos at all
  const dryRun = [];
  for (const m of fightMods.slice().sort((a, b) => stageOf(a.module_id) - stageOf(b.module_id))) {
    const g = (m.rounds || []).filter((r) => r.combo_spec?.allowed_strikes?.length).length;
    if (g === 0) dryRun.push(stageOf(m.module_id));
  }
  let run = [];
  for (const n of dryRun.concat([-99])) {
    if (run.length && n === run[run.length - 1] + 1) run.push(n);
    else { if (run.length >= 2) flags.push(`Stages ${run.join(", ")} are consecutive with **no combos called at all** — a fight-only player goes ${run.length} full stages dry. Convert one round per stage to \`mixed_with_cue\`.`); run = [n]; }
  }

  // ── assemble ────────────────────────────────────────────────────────────
  out.push(`**Fight round totals:** ${generated + cue} rounds — **${generated} generated** ` +
    `(carry a \`combo_spec\` with \`allowed_strikes\`, so the generator writes the combos live) and ` +
    `**${cue} cue-based** (coached rather than combo-called).` +
    (mixed ? ` ${mixed} of the generated rounds are **mixed** (\`mixed_with_cue\`).` : ""), "");
  out.push(flags.length
    ? `**Review status: ${flags.length} FLAG${flags.length > 1 ? "S" : ""}** — see the bottom of this sheet.`
    : "**Review status: no automatic flags.** Ready for playtest.", "");
  out.push(...body);
  out.push("---", "", "# Flags", "");
  if (!flags.length) out.push("None. Every fight module generates combos, every fit module carries a counted",
    "prescription, tiers are present on both halves, and the campaign fits the",
    "Arcade ladder.", "");
  else flags.forEach((f, i) => out.push(`**${i + 1}.** ${f}`, ""));
  out.push("> Automatic flags only catch the patterns found in the ARC_BAKI review",
    "> (missing prescriptions, missing tiers, combo droughts, single-strike",
    "> monotony, single-long-round modules, stage-count truncation). Read the",
    "> stage tables above for anything a script can't judge.", "");

  return { markdown: out.join("\n"), flagCount: flags.length, stages: stages.length, modules: modules.length, generated, cue };
}

// ── cli ───────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const toStdout = args.includes("--stdout");
const ids = args.includes("--all")
  ? readdirSync(CAMPAIGNS).filter((d) => existsSync(join(CAMPAIGNS, d, "campaign.json"))).sort()
  : args.filter((a) => !a.startsWith("--"));

if (!ids.length) {
  console.error("usage: node protocol-src/scripts/review-campaign.mjs <CAMPAIGN_ID> [--stdout]");
  console.error("       node protocol-src/scripts/review-campaign.mjs --all");
  console.error("\navailable: " + readdirSync(CAMPAIGNS).sort().join(", "));
  process.exit(1);
}

if (!existsSync(REVIEWS)) mkdirSync(REVIEWS, { recursive: true });
for (const cid of ids) {
  if (!existsSync(join(CAMPAIGNS, cid))) { console.error(`✗ unknown campaign: ${cid}`); process.exitCode = 1; continue; }
  const r = review(cid);
  if (toStdout) { console.log(r.markdown); continue; }
  const path = join(REVIEWS, `${cid}-review.md`);
  writeFileSync(path, r.markdown + "\n");
  console.log(`${cid.padEnd(18)} ${r.stages} stages · ${r.modules} modules · ` +
    `${r.generated} gen / ${r.cue} cue · ${r.flagCount} flag(s) → protocol-src/reviews/${cid}-review.md`);
}
